export function getProviderLogoKey(provider: string, name?: string): string | null {
  const candidates = [provider, name]
    .filter((value): value is string => Boolean(value))
    .map((value) => value.trim().toLowerCase().replace(/[_\s]+/g, "-"));

  for (const candidate of candidates) {
    if (PROVIDER_MARKS[candidate]) return candidate;
    if (PROVIDER_ALIASES[candidate]) return PROVIDER_ALIASES[candidate];
    for (const [needle, key] of [
      ["anthropic", "anthropic"],
      ["claude", "anthropic"],
      ["openrouter", "openrouter"],
      ["openai", "openai"],
      ["ollama", "ollama"],
      ["gemini", "gemini"],
      ["google", "gemini"],
      ["groq", "groq"],
      ["moonshot", "kimi"],
      ["kimi", "kimi"],
      ["mistral", "mistral"],
      ["deepseek", "deepseek"],
      ["qwen", "qwen"],
      ["grok", "xai"],
      ["xai", "xai"],
      ["minimax", "minimax"],
      ["cerebras", "cerebras"],
      ["z.ai", "zai"],
      ["z-ai", "zai"],
      ["lmstudio", "lmstudio"],
      ["lm-studio", "lmstudio"],
    ] as const) {
      if (candidate.includes(needle)) return key;
    }
  }
  return null;
}

